// Builds dist/x-slop-hide.user.js from the extension sources, so the userscript
// and the extension run the same lib.js and content.js bytes.
//   node scripts/build-userscript.mjs          write the file
//   node scripts/build-userscript.mjs --check  exit 1 if the committed file is stale
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const manifest = JSON.parse(read('manifest.json'));

export function buildUserscript() {
  const header = [
    '// ==UserScript==',
    '// @name         x-slop-hide',
    '// @namespace    https://github.com/StartupBros-com/x-slop-hide',
    `// @version      ${manifest.version}`,
    `// @description  ${manifest.description}`,
    '// @match        https://x.com/*',
    '// @match        https://twitter.com/*',
    '// @match        https://mobile.x.com/*',
    '// @match        https://mobile.twitter.com/*',
    '// @run-at       document-start',
    '// @grant        GM_getValue',
    '// @grant        GM_setValue',
    '// @grant        GM_xmlhttpRequest',
    '// @grant        GM_registerMenuCommand',
    '// @grant        GM_addValueChangeListener',
    '// @connect      clankwall.vogel.dev',
    '// ==/UserScript==',
    '// Generated by scripts/build-userscript.mjs from src/. Edit the sources, then rebuild.',
    '',
  ].join('\n');
  const parts = ['src/lib.js', 'src/userscript-adapter.js', 'src/content.js'].map(
    (p) => `// ---- ${p} ----\n${read(p).trimEnd()}\n`,
  );
  return header + parts.join('\n');
}

const out = join(root, 'dist', 'x-slop-hide.user.js');
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const built = buildUserscript();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch (_) {
      // missing counts as stale
    }
    if (current !== built) {
      console.error('dist/x-slop-hide.user.js is stale: run node scripts/build-userscript.mjs');
      process.exit(1);
    }
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, built);
    console.log(`wrote ${out} (${built.length} bytes)`);
  }
}
